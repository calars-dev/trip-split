-- Trip Split — 여행이 며칠짜리인지
--
-- 순서는 어느 쪽이어도 된다. 칸 하나를 더할 뿐이라 지금 도는 앱이 그대로 돌고,
-- 옛 앱은 이 칸을 읽지도 쓰지도 않는다. 여러 번 돌려도 안전하다.
--
-- 왜 필요한가
--   일차 칩은 지금까지 "아는 것보다 하루 더"까지만 그렸다. 여행 중에는 날이
--   갈수록 칩이 따라 늘어나 문제가 없지만, **출발 전**에는 오늘이 '준비'라
--   1일차와 2일차밖에 안 나온다. 떠나기 전에 4일차 투어를 미리 넣을 수가 없다.
--   여행이 며칠인지 알면 그 날까지 한 번에 그릴 수 있다.
--
--   비워두면(null) 지금까지와 똑같이 동작한다.

-- 값 범위(1~60)는 입력 화면이 막는다. 이 칸을 쓰는 건 방을 연 사람뿐이고,
-- 범위를 벗어난 값이 들어와도 일차 칩이 조금 많아질 뿐 계산은 어긋나지 않는다.
alter table public.rooms add column if not exists day_count smallint;

-- ── 이시가키는 4박 5일 ──────────────────────────────────────────────
update public.rooms set day_count = 5 where id = 'qx73ifx';

-- 확인: 5 가 나와야 한다
select id, name, start_date, day_count from public.rooms where id = 'qx73ifx';
